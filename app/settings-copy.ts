export type SettingsCopyKey = keyof typeof SETTINGS_COPY;

/** 纯函数版，测试与非组件代码用。{name} 占位符按 values 替换，缺的原样保留。 */
export function settingsText(locale: UiLocale, key: SettingsCopyKey, values: Record<string, string | number> = {}) {
  return SETTINGS_COPY[key][locale === "ja" ? 1 : 0].replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export function useSettingsCopy() {
  const { locale } = useUiLocale();
  const t = (key: SettingsCopyKey, values?: Record<string, string | number>) => settingsText(locale, key, values);
  const pick = (pair: readonly [string, string]) => pair[locale === "ja" ? 1 : 0];
  return { t, pick, locale };
}
